const Ctx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string, v?: Record<string, string | number>) => string;
}>({ lang: 'en', setLang: () => {}, t: (k) => k });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getStoredLang() || 'en');
  // `bump` forces a re-render even when the picked language equals the current
  // one (English is the default, so choosing English wouldn't change state and
  // React would bail out) — screens that branch on `getStoredLang()` being set
  // need to hear about the choice itself, not just a change of language.
  const [, bump] = useState(0);
  const setLang = (l: Lang) => { storeLang(l); setLangState(l); bump((n) => n + 1); };
  const t = (k: string, v?: Record<string, string | number>) => {
    let s = S[k]?.[lang] ?? S[k]?.en ?? k;
    if (v) for (const [key, val] of Object.entries(v)) s = s.replace(new RegExp(`\\{${key}\\}`, 'g'), String(val));
    return s;
  };
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}
export const useT = () => useContext(Ctx);
